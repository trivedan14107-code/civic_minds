alter table public.departments enable row level security;
alter table public.issues enable row level security;
alter table public.issue_reports enable row level security;
alter table public.status_events enable row level security;

create policy departments_read on public.departments for select to anon, authenticated using (true);
create policy issues_read on public.issues for select to authenticated using (true);
create policy issues_create on public.issues for insert to authenticated with check (true);
create policy issues_update on public.issues for update to authenticated using (true) with check (true);
create policy issue_reports_read on public.issue_reports for select to authenticated using (true);
create policy issue_reports_create on public.issue_reports for insert to authenticated with check (true);
create policy status_events_read on public.status_events for select to authenticated using (true);
create policy status_events_create on public.status_events for insert to authenticated with check (true);

-- Storage buckets are created separately in the dashboard or with the Storage API.
-- These policies allow authenticated clients to upload/read only CivicMind media.
create policy "authenticated upload issue images" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'issue-images');
create policy "authenticated read issue images" on storage.objects
  for select to authenticated
  using (bucket_id = 'issue-images');
create policy "authenticated upload cctv frames" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'cctv-frames');
create policy "authenticated read cctv frames" on storage.objects
  for select to authenticated
  using (bucket_id = 'cctv-frames');
